def pp(hv=6.3, ha=0.3, socket="B7G", cutoff="sharp", gm=None, va=300, vibe=0, notes="", elements=None):
    """small-signal pentode. Default elements: single pentode section."""
    return {"cat": "pentode_pre", "socket": socket, "hv": hv, "ha": ha,
            "va_max": va, "gm": gm, "cutoff": cutoff, "vibe": vibe,
            "elements": elements or ["pentode"], "notes": notes}

def tp(mu, hv=6.3, ha=0.3, socket="noval", va=300, vibe=0, notes="", n=2, elements=None):
    """triode preamp. n = number of triode sections (default 2 = dual)."""
    return {"cat": "triode_pre", "socket": socket, "hv": hv, "ha": ha,
            "va_max": va, "mu": mu, "vibe": vibe,
            "elements": elements or ["triode"] * n, "notes": notes}

def po(pd, hv=6.3, ha=0.76, socket="noval", va=300, vibe=0, notes="", kind="power_pentode", elements=None):
    """power tube. kind = power_pentode | beam_power | power_triode (used as element label)."""
    return {"cat": "power", "socket": socket, "hv": hv, "ha": ha,
            "va_max": va, "pd": pd, "vibe": vibe,
            "elements": elements or [kind], "notes": notes}

def combo(mu, pd, hv=6.3, ha=0.75, socket="noval", va=300, vibe=0, notes="", elements=None):
    """triode-pentode combo tube (preamp triode + SE power pentode)."""
    return {"cat": "combo", "socket": socket, "hv": hv, "ha": ha,
            "va_max": va, "mu": mu, "pd": pd, "vibe": vibe,
            "elements": elements or ["triode", "power_pentode"], "notes": notes}

def rect(hv=5.0, ha=2.0, socket="octal", va=350, vibe=0, notes="", n=2, elements=None):
    """rectifier. n = number of diode sections (default 2 = full-wave)."""
    return {"cat": "rectifier", "socket": socket, "hv": hv, "ha": ha,
            "va_max": va, "vibe": vibe,
            "elements": elements or ["diode"] * n, "notes": notes}

def damp(hv=6.3, ha=1.2, socket="noval", notes="", n=1, elements=None):
    return {"cat": "damper", "socket": socket, "hv": hv, "ha": ha,
            "elements": elements or ["damper_diode"] * n, "notes": notes}

def vr(v_reg, socket="B7G", notes="", elements=None):
    return {"cat": "regulator", "socket": socket, "hv": 0, "ha": 0,
            "va_max": v_reg,
            "elements": elements or ["gas_regulator"], "notes": notes}

def defl(pd, hv=6.3, ha=1.6, socket="octal", va=700, notes="", kind="beam_power", elements=None):
    return {"cat": "deflection", "socket": socket, "hv": hv, "ha": ha,
            "va_max": va, "pd": pd,
            "elements": elements or [kind], "notes": notes}

def conv(hv=6.3, ha=0.3, socket="noval", notes="", elements=None):
    return {"cat": "converter", "socket": socket, "hv": hv, "ha": ha,
            "va_max": 300,
            "elements": elements or ["pentagrid"], "notes": notes}

def eye(hv=6.3, ha=0.3, socket="octal", notes="", elements=None):
    # Magic-eye tubes have an internal triode driver plus the fluorescent target.
    return {"cat": "magic_eye", "socket": socket, "hv": hv, "ha": ha,
            "elements": elements or ["magic_eye", "triode"], "notes": notes}

def alias(of, notes="", **overrides):
    r = {"alias_of": of}
    if notes: r["notes"] = notes
    r.update(overrides)
    return r

def other(socket=None, hv=None, ha=None, notes="", elements=None):
    r = {"cat": "other", "notes": notes}
    if socket: r["socket"] = socket
    if hv is not None: r["hv"] = hv
    if ha is not None: r["ha"] = ha
    if elements: r["elements"] = elements
    return r

